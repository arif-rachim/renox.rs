// `.renox/types/` (#43; docs/12-developer-experience.md, "Type safety"):
// what `renox dev` knows about the app, as declarations the editor checks
// against. Generated on every successful build, never read by the runtime.
//
//   .renox/types/routes.d.ts     RouteParams per module id, LoaderContextOf,
//                                ActionContextOf, Fragments per page
//   .renox/types/db.d.ts         Tables: one row type per app table, from
//                                the migrations run in memory (bun:sqlite)
//   .renox/types/index.d.ts      re-exports both
//   .renox/types/modules.d.ts    Modules and ModuleCtx<M> of the installed
//                                modules (#236, ./modules.ts), and
//   .renox/types/renox-modules.d.ts  `declare module "renox:modules"`
//
// Use in a page module:
//   import type { LoaderContextOf } from "../../.renox/types";
//   export async function load({ params }: LoaderContextOf<"pages/products/[id]">) { params.id; }

import { Database } from "bun:sqlite";
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import type { Route } from "../routes.ts";
import { modulesDts } from "./modules.ts";
import { installedModules } from "../modules/build.ts";
import type { CompiledTemplate } from "../templates-compile.ts";

const HEADER = "// Generated by renox dev (#43). Do not edit: it is rewritten on every build.\n";

const str = (s: string): string => JSON.stringify(s);

/** `:id` → `id: string`, `*slug` → `slug: string[]`. */
function paramsType(pattern: string): string {
  const fields = pattern
    .split("/")
    .filter((s) => s.startsWith(":") || s.startsWith("*"))
    .map((s) => (s.startsWith(":") ? `${s.slice(1)}: string` : `${s.slice(1)}: string[]`));
  return fields.length ? `{ ${fields.join("; ")} }` : "Record<string, never>";
}

/** routes.d.ts: params per module, the page contexts, fragment names per page. */
export function routesDts(routes: Route[], templates: Record<string, CompiledTemplate>): string {
  const params = new Map<string, string>();
  for (const r of routes) {
    const id = r.module ?? (r.kind === "page" ? r.template : undefined);
    if (id) params.set(id, paramsType(r.path));
  }
  const fragments = Object.entries(templates)
    .filter(([, t]) => t.kind === "page")
    .map(([id, t]) => {
      const names = Object.keys(t.fragments ?? {});
      return `  ${str(id)}: ${names.length ? names.map(str).join(" | ") : "never"};`;
    });
  return `${HEADER}import type { ActionContext, LoaderContext } from "renox";

/** Route parameters per module id (file names: [id] is a string, [...slug] a list). */
export interface RouteParams {
${[...params].map(([id, t]) => `  ${str(id)}: ${t};`).join("\n")}
}

/** Fragment names per page template (the fragment map). */
export interface Fragments {
${fragments.join("\n")}
}

export type ParamsOf<M extends keyof RouteParams> = RouteParams[M];
export type FragmentOf<M extends keyof Fragments> = Fragments[M];

/** \`load\`'s context with the page's own params and fragment names. */
export type LoaderContextOf<M extends keyof RouteParams> = Omit<LoaderContext, "params" | "fragment"> & {
  readonly params: RouteParams[M];
  readonly fragment: (M extends keyof Fragments ? Fragments[M] : never) | null;
};

/** An action's context with the page's own params and fragment names. */
export type ActionContextOf<M extends keyof RouteParams> = Omit<ActionContext, "params" | "fragment"> & {
  readonly params: RouteParams[M];
  readonly fragment: (M extends keyof Fragments ? Fragments[M] : never) | null;
};

/** What an action may name in \`fragments\`. */
export type ActionFragments<M extends keyof Fragments> = { fragments?: Fragments[M][] };
`;
}

/** The TypeScript type of a column, by SQLite type affinity (sqlite.org/datatype3, 3.1). */
export function columnType(declared: string): string {
  const t = declared.toUpperCase();
  if (t.includes("INT")) return "number";
  if (t.includes("CHAR") || t.includes("CLOB") || t.includes("TEXT")) return "string";
  if (t === "") return "unknown";
  if (t.includes("BLOB")) return "Uint8Array";
  if (t.includes("REAL") || t.includes("FLOA") || t.includes("DOUB")) return "number";
  return "number";
}

const MIGRATION = /^\d{3}_[a-z0-9_]{1,64}\.sql$/u;

interface Column {
  name: string;
  type: string;
  notnull: number;
  pk: number;
}

/**
 * db.d.ts: the installed modules' migrations (renox.lock order, #235), then
 * the app's, applied to an in-memory database, then introspected.
 */
export function dbDts(project: string): string {
  const dir = join(project, "migrations");
  const db = new Database(":memory:");
  try {
    for (const m of installedModules(project).modules) {
      const md = join(m.tree, "migrations");
      if (!existsSync(md)) continue;
      for (const f of readdirSync(md).filter((n) => MIGRATION.test(n)).sort()) db.exec(readFileSync(join(md, f), "utf8"));
    }
    if (existsSync(dir)) {
      for (const f of readdirSync(dir).filter((n) => MIGRATION.test(n)).sort()) db.exec(readFileSync(join(dir, f), "utf8"));
    }
    const tables = db
      .query("select name from sqlite_master where type = 'table' and name not like 'sqlite_%' order by name")
      .all() as { name: string }[];
    const rows = tables.map(({ name }) => {
      const cols = db.query(`select name, type, "notnull", pk from pragma_table_info(?)`).all(name) as Column[];
      const fields = cols.map((c) => `    ${/^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(c.name) ? c.name : str(c.name)}: ${columnType(c.type)}${c.notnull || c.pk ? "" : " | null"};`);
      return `  ${str(name)}: {\n${fields.join("\n")}\n  };`;
    });
    return `${HEADER}
/** One row type per table, from migrations/ (INTEGER and REAL are number; a value beyond 2^53 - 1 arrives as bigint). */
export interface Tables {
${rows.join("\n")}
}

export type TableName = keyof Tables;
export type RowOf<T extends TableName> = Tables[T];
/** The tables of one prefix (\`app\` or an installed module): \`TablesOf<"auth">\`. */
export type TablesOf<P extends string> = { [K in keyof Tables as K extends \`\${P}__\${string}\` ? K : never]: Tables[K] };
`;
  } finally {
    db.close();
  }
}

/** Writes `.renox/types/` (each file replaced atomically). */
export function writeTypes(project: string, routes: Route[], templates: Record<string, CompiledTemplate>): string {
  const out = join(project, ".renox", "types");
  mkdirSync(out, { recursive: true });
  const files: Record<string, string> = {
    "routes.d.ts": routesDts(routes, templates),
    "db.d.ts": dbDts(project),
    "index.d.ts": `${HEADER}export * from "./routes";\nexport * from "./db";\n`,
  };
  // Installed modules (#236): modules.d.ts and the ambient `renox:modules`.
  const mods = modulesDts(project);
  if (mods !== null) {
    files["modules.d.ts"] = mods.modules;
    files["renox-modules.d.ts"] = mods.ambient;
  }
  for (const [name, text] of Object.entries(files)) {
    const tmp = join(out, `${name}.tmp`);
    writeFileSync(tmp, text);
    renameSync(tmp, join(out, name));
  }
  return out;
}
