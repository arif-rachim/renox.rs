// .renox/types/modules.d.ts and renox-modules.d.ts (#236;
// docs/contracts/manifest.md section 1; docs/10-modules.md): the types of
// every installed module, generated from the lock and the manifests.
//
// - Services: `ServicesOf<typeof import("<tree>/services.ts")>`. The
//   signatures are the module's own TypeScript, inferred by the type
//   checker (TypeScript 7 has no JavaScript compiler API to read them
//   with), so they never drift from the source.
// - Event payloads and hook arguments: from the manifest's JSON schemas
//   (`schemaToTs`, a small subset: object, string, number, integer,
//   boolean, null, array, enum, const, oneOf/anyOf, required).
// - Config: from `[config]` declarations.
//
// Use in a module:  import type { ModuleCtx } from "../../.renox/types/modules";
//                   async function getActivePlan(ctx: ModuleCtx<"billing">, userId: string) { ... }

import { existsSync } from "node:fs";
import { join, relative } from "node:path";

import { type Json, type JsonObject, isObject } from "../schema.ts";
import { readLock } from "../modules/lock.ts";
import { obj, readManifest, strings } from "../modules/manifest.ts";
import { fetchTree } from "../modules/resolve.ts";

const HEADER = "// Generated by renox (#236) from renox.lock and the module manifests. Do not edit: it is rewritten on every build.\n";
const str = (s: string): string => JSON.stringify(s);
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/u;
const prop = (k: string): string => (IDENT.test(k) ? k : str(k));

/** A TypeScript type for a JSON schema of the manifest keyword subset; `unknown` for anything else. */
export function schemaToTs(schema: Json | undefined, indent = ""): string {
  if (!isObject(schema)) return "unknown";
  if ("const" in schema) return JSON.stringify(schema.const);
  if (Array.isArray(schema.enum)) return schema.enum.map((v) => JSON.stringify(v)).join(" | ") || "never";
  for (const k of ["oneOf", "anyOf"] as const) if (Array.isArray(schema[k])) return (schema[k] as Json[]).map((s) => schemaToTs(s, indent)).join(" | ");
  const types = Array.isArray(schema.type) ? (schema.type as string[]) : typeof schema.type === "string" ? [schema.type] : [];
  if (types.length > 1) return types.map((t) => schemaToTs({ ...schema, type: t }, indent)).join(" | ");
  switch (types[0]) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array": {
      const item = schemaToTs(schema.items, indent);
      return /[|&]/u.test(item) ? `(${item})[]` : `${item}[]`;
    }
    case "object": {
      const props = obj(schema.properties);
      const required = new Set(strings(schema.required));
      const inner = `${indent}  `;
      const fields = Object.entries(props).map(([k, s]) => `${inner}${prop(k)}${required.has(k) ? "" : "?"}: ${schemaToTs(s, inner)};`);
      const extra = schema.additionalProperties;
      if (extra === undefined || extra === true) fields.push(`${inner}[key: string]: unknown;`);
      else if (isObject(extra)) fields.push(`${inner}[key: string]: ${schemaToTs(extra, inner)};`);
      return fields.length ? `{\n${fields.join("\n")}\n${indent}}` : "Record<string, never>";
    }
    default:
      return "unknown";
  }
}

/** The value type of one `[config]` declaration. */
function configType(decl: JsonObject): string {
  switch (decl.type) {
    case "enum":
      return strings(decl.values).map(str).join(" | ") || "never";
    case "int":
      return "number";
    case "bool":
      return "boolean";
    default:
      return "string";
  }
}

/** An import specifier from `.renox/types/` to a file (posix separators, `./` prefix). */
const specifier = (from: string, to: string): string => {
  const r = relative(from, to).split("\\").join("/");
  return r.startsWith(".") ? r : `./${r}`;
};

/** modules.d.ts and renox-modules.d.ts; `null` when the app has no lock or no modules. */
export function modulesDts(project: string): { modules: string; ambient: string } | null {
  const { entries } = readLock(project);
  if (entries === null || entries.length === 0) return null;
  const out = join(project, ".renox", "types");
  const specs: string[] = [];
  for (const e of entries) {
    const { tree } = fetchTree(project, e.name, e.source);
    const { manifest } = readManifest(tree, `${e.name}/module.toml`);
    const doc = manifest?.doc ?? {};
    const exports = obj(doc.exports);
    const servicesFile = ["services.ts", "services.js"].map((f) => join(tree, f)).find((f) => existsSync(f));
    const services = servicesFile !== undefined && strings(Object.keys(obj(exports.services))).length > 0 ? `ServicesOf<typeof import(${str(specifier(out, servicesFile))})>` : "Record<string, never>";
    const events = Object.entries(obj(exports.events)).map(([n, def]) => `      ${str(n)}: ${schemaToTs(obj(def).payload, "      ")};`);
    const hooks = Object.entries(obj(exports.hooks)).map(
      ([n, def]) => `      ${str(n)}: { args: ${schemaToTs(obj(def).args, "        ")}; result: ${obj(def).result === undefined ? "void" : schemaToTs(obj(def).result, "        ")} };`,
    );
    const decls = obj(doc.config);
    const config = Object.entries(decls).map(([k, raw]) => {
      const d = obj(raw);
      const optional = d.default === undefined && d.required === false;
      return `      ${prop(k)}${optional ? "?" : ""}: ${configType(d)};`;
    });
    const block = (lines: string[]) => (lines.length ? `{\n${lines.join("\n")}\n    }` : "Record<never, never>");
    specs.push(`  ${str(e.name)}: {\n    services: ${services};\n    events: ${block(events)};\n    hooks: ${block(hooks)};\n    config: ${block(config)};\n  };`);
  }
  const modules = `${HEADER}import type { ModuleCtx as ModuleCtxOf, ServicesOf } from "renox";

/** Every installed module, in renox.lock order. */
export interface Modules {
${specs.join("\n")}
}

export type ModuleName = keyof Modules;

/** The ctx a module's services, hooks and handlers receive; "app" for the app's own code. */
export type ModuleCtx<M extends ModuleName | "app" = "app"> = ModuleCtxOf<Modules, M>;

/** The payload type of an exported event. */
export type EventPayload<M extends ModuleName, E extends keyof Modules[M]["events"]> = Modules[M]["events"][E];
`;
  const ambient = `${HEADER}// \`import { auth } from "renox:modules"\`: the broker's service proxies (ops.md section 15.2).
declare module "renox:modules" {
${entries.map((e) => `  export const ${e.name}: import("./modules").Modules[${str(e.name)}]["services"];`).join("\n")}
}
`;
  return { modules, ambient };
}
