//! Render path B (ADR D7, `docs/08-template-engine.md`, "Two render
//! paths"): the compiled templates as one JavaScript module that renders in
//! the tenant isolate, so the data is used where the loader produced it and
//! never crosses into Rust.
//!
//! The input is the same as path A's: the minijinja sources of
//! [`CompiledTemplates`]. They are parsed with minijinja's own parser and the
//! syntax tree is translated to JavaScript, so both paths start from one
//! intermediate representation and one set of compiler checks. The module
//! carries a small runtime (`runtime.js`) that reproduces the renderer's
//! semantics: HTML escaping without `/`, `none`/`undefined` printing nothing,
//! chainable undefined lookups, minijinja truthiness and equality, the
//! platform filters for `en-AE` and `ar-AE`, and `__url`.
//!
//! ```js
//! import { render, renderFragment } from "./templates.js";
//! render("pages/products/index", data, { csp_nonce, locale: "en-AE" });
//! renderFragment("pages/products/index", "product_list", data, cx);
//! ```
//!
//! Limits: path B runs on the tenant's CPU and heap. minijinja's fuel has no
//! equivalent (V8 has no instruction counter), so the bound is the isolate's
//! CPU limit, enforced in Rust by the runtime watchdog. The module also
//! counts loop iterations and output bytes against the same numbers as
//! [`RenderLimits::DEFAULT`](crate::RenderLimits) so a runaway template stops
//! with the same error codes; those two checks run in JavaScript and are a
//! convenience, not the enforcement.
//!
//! Prototype scope (#42): the subset the compiler emits for `examples/shop`
//! and the fixture set. Not covered, and refused with an [`EmitError`]: the
//! `date`, `ago`, and `round` filters and module filters, slices, macros,
//! `{% set %}` blocks, loop filters, tuple loop targets, and non-constant
//! `extends`/`include` names. Known difference: an integral float computed by
//! template arithmetic (`4 / 2`) prints `2.0` on path A and `2` on path B;
//! data never carries one, since the loader's JSON drops the `.0`. A
//! fragment renders its block only; path A evaluates the whole page first
//! (`Renderer::render_to`), so a page-level error (a filter on data the
//! fragment's loader skipped) fails the fragment on path A and not on B.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use minijinja::machinery::ast::{self, BinOpKind, CallArg, CompareOpKind, Expr, Stmt, UnaryOpKind};
use minijinja::machinery::parse;
use minijinja::syntax::SyntaxConfig;
use minijinja::value::{Value, ValueKind};

use crate::CompiledTemplates;

/// The runtime every emitted module starts with.
const RUNTIME: &str = include_str!("runtime.js");

/// Filters the runtime implements (`runtime.js`, `F`).
const FILTERS: &[&str] = &[
    "money", "number", "truncate", "json", "upper", "lower", "default", "length", "first", "last",
    "join", "trim", "abs", "safe", "__loop", "__url",
];

/// Tests the runtime implements (`runtime.js`, `TESTS`).
const TESTS: &[&str] = &[
    "defined",
    "undefined",
    "none",
    "true",
    "false",
    "number",
    "string",
    "sequence",
    "mapping",
    "even",
    "odd",
    "divisibleby",
    "eq",
    "ne",
    "lt",
    "le",
    "gt",
    "ge",
    "in",
    "startingwith",
    "endingwith",
];

/// A template path B cannot render.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("template {template}: {reason}")]
pub struct EmitError {
    pub template: String,
    pub reason: String,
}

/// Emits one ES module rendering every template of `compiled`.
pub fn emit_module(compiled: &CompiledTemplates) -> Result<String, EmitError> {
    let mut out = String::with_capacity(RUNTIME.len() + 4096);
    out.push_str("// Generated by renox-template emit_js (render path B). Do not edit.\n");
    out.push_str(RUNTIME);
    out.push_str("\nconst T = Object.create(null);\n");
    for (id, source) in compiled.sources() {
        let js = emit_template(id, source).map_err(|reason| EmitError {
            template: id.to_string(),
            reason,
        })?;
        let _ = writeln!(out, "T[{}] = {js};", js_str(id));
    }
    out.push_str("export const templates = T;\n");
    out.push_str(
        "export function render(id, data, cx) { return renderTemplate(T, id, null, data, cx); }\n",
    );
    out.push_str(
        "export function renderFragment(id, block, data, cx) { return renderTemplate(T, id, block, data, cx); }\n",
    );
    Ok(out)
}

/// One template as a JS object literal: `{ parent, body, blocks }`.
fn emit_template(id: &str, source: &str) -> Result<String, String> {
    let tree = parse(source, id, SyntaxConfig::default()).map_err(|e| e.to_string())?;
    let Stmt::Template(t) = tree else {
        return Err("parser did not return a template".into());
    };
    let mut cx = Cx::default();
    // A template that extends another renders only through its blocks; the
    // text around them is discarded, as minijinja does.
    let mut parent = None;
    for stmt in &t.children {
        if let Stmt::Extends(e) = stmt {
            parent = Some(const_str(&e.name).ok_or("`extends` with a computed name")?);
        }
    }
    let body = if parent.is_some() {
        for stmt in &t.children {
            if matches!(stmt, Stmt::Set(_) | Stmt::WithBlock(_)) {
                return Err("statements outside blocks in a template that extends".into());
            }
            cx.collect_blocks(stmt)?;
        }
        String::new()
    } else {
        cx.stmts(&t.children, "s")?
    };
    let mut blocks = String::new();
    for (name, code) in &cx.blocks {
        let _ = write!(
            blocks,
            "{}: function (s, o, B) {{ let $t; {code}}},",
            js_str(name)
        );
    }
    Ok(format!(
        "{{ parent: {}, body: function (s, o, B) {{ let $t; {body}}}, blocks: {{ {blocks} }} }}",
        parent.map(|p| js_str(&p)).unwrap_or_else(|| "null".into()),
    ))
}

#[derive(Default)]
struct Cx {
    /// Block name -> body code. A block is emitted once and called through
    /// the block table `B`, so a child template's block replaces it.
    blocks: BTreeMap<String, String>,
    /// Counter for scope variable names.
    next: usize,
}

impl Cx {
    fn fresh(&mut self) -> String {
        self.next += 1;
        format!("s{}", self.next)
    }

    /// Blocks of a template that extends: only the block bodies matter.
    fn collect_blocks(&mut self, stmt: &Stmt<'_>) -> Result<(), String> {
        match stmt {
            Stmt::Block(b) => {
                self.block(b)?;
            }
            Stmt::IfCond(i) => {
                for s in i.true_body.iter().chain(&i.false_body) {
                    self.collect_blocks(s)?;
                }
            }
            Stmt::ForLoop(f) => {
                for s in f.body.iter().chain(&f.else_body) {
                    self.collect_blocks(s)?;
                }
            }
            _ => {}
        }
        Ok(())
    }

    fn block(&mut self, b: &ast::Block<'_>) -> Result<(), String> {
        let code = self.stmts(&b.body, "s")?;
        if self.blocks.insert(b.name.to_string(), code).is_some() {
            return Err(format!("block `{}` defined twice", b.name));
        }
        Ok(())
    }

    fn stmts(&mut self, stmts: &[Stmt<'_>], s: &str) -> Result<String, String> {
        let mut out = String::new();
        for stmt in stmts {
            self.stmt(stmt, s, &mut out)?;
        }
        Ok(out)
    }

    fn stmt(&mut self, stmt: &Stmt<'_>, s: &str, out: &mut String) -> Result<(), String> {
        match stmt {
            Stmt::Template(t) => out.push_str(&self.stmts(&t.children, s)?),
            Stmt::EmitRaw(r) => {
                let _ = write!(out, "o.w({});", js_str(r.raw));
            }
            Stmt::EmitExpr(e) => {
                let _ = write!(out, "o.emit({});", self.expr(&e.expr, s)?);
            }
            Stmt::IfCond(i) => {
                let _ = write!(
                    out,
                    "if (truthy({})) {{ {}}} else {{ {}}}",
                    self.expr(&i.expr, s)?,
                    self.stmts(&i.true_body, s)?,
                    self.stmts(&i.false_body, s)?
                );
            }
            Stmt::ForLoop(f) => self.for_loop(f, s, out)?,
            Stmt::WithBlock(w) => {
                let inner = self.fresh();
                let _ = write!(out, "{{ const {inner} = Object.create({s}); ");
                for (target, value) in &w.assignments {
                    let name = var_name(target)?;
                    let _ = write!(
                        out,
                        "{inner}[{}] = {};",
                        js_str(name),
                        self.expr(value, &inner)?
                    );
                }
                let _ = write!(out, "{}}}", self.stmts(&w.body, &inner)?);
            }
            Stmt::Set(set) => {
                let name = var_name(&set.target)?;
                let _ = write!(out, "{s}[{}] = {};", js_str(name), self.expr(&set.expr, s)?);
            }
            Stmt::Block(b) => {
                self.block(b)?;
                let _ = write!(out, "B[{}]({s}, o, B);", js_str(b.name));
            }
            Stmt::Include(i) => {
                if i.ignore_missing {
                    return Err("`include ignore missing`".into());
                }
                let name = const_str(&i.name).ok_or("`include` with a computed name")?;
                let _ = write!(out, "include(T, {}, {s}, o);", js_str(&name));
            }
            Stmt::Extends(_) => return Err("`extends` inside a template body".into()),
            Stmt::AutoEscape(_) => return Err("`autoescape` blocks".into()),
            Stmt::FilterBlock(_) => return Err("`filter` blocks".into()),
            Stmt::SetBlock(_) => return Err("`set` blocks".into()),
            Stmt::Import(_) | Stmt::FromImport(_) => return Err("imports".into()),
            Stmt::Do(_) => return Err("`do`".into()),
            // Macros and loop controls exist only with minijinja features
            // this crate does not enable; the parser rejects them.
            #[allow(unreachable_patterns)]
            _ => return Err("unsupported statement".into()),
        }
        Ok(())
    }

    fn for_loop(&mut self, f: &ast::ForLoop<'_>, s: &str, out: &mut String) -> Result<(), String> {
        if f.filter_expr.is_some() || f.recursive {
            return Err("loop filters and recursive loops".into());
        }
        let item = var_name(&f.target).map_err(|_| "tuple loop targets".to_string())?;
        let n = self.next + 1;
        let inner = self.fresh();
        let _ = write!(
            out,
            "{{ const it{n} = iter({}); if (it{n}.length) {{ for (let i{n} = 0; i{n} < it{n}.length; i{n}++) {{ const {inner} = Object.create({s}); {inner}.loop = loopVar(i{n}, it{n}.length); {inner}[{}] = it{n}[i{n}]; {}}} }} else {{ {}}} }}",
            self.expr(&f.iter, s)?,
            js_str(item),
            self.stmts(&f.body, &inner)?,
            self.stmts(&f.else_body, s)?,
        );
        Ok(())
    }

    fn expr(&mut self, e: &Expr<'_>, s: &str) -> Result<String, String> {
        Ok(match e {
            Expr::Var(v) => format!("{s}[{}]", js_str(v.id)),
            Expr::Const(c) => const_js(&c.value)?,
            Expr::GetAttr(g) => format!("getItem({}, {})", self.expr(&g.expr, s)?, js_str(g.name)),
            Expr::GetItem(g) => format!(
                "getItem({}, {})",
                self.expr(&g.expr, s)?,
                self.expr(&g.subscript_expr, s)?
            ),
            Expr::UnaryOp(u) => match u.op {
                UnaryOpKind::Not => format!("!truthy({})", self.expr(&u.expr, s)?),
                UnaryOpKind::Neg => format!("neg({})", self.expr(&u.expr, s)?),
            },
            Expr::BinOp(b) => {
                let l = self.expr(&b.left, s)?;
                let r = self.expr(&b.right, s)?;
                match b.op {
                    // `$t` is declared in every emitted function; the left
                    // side is evaluated in full before it is assigned.
                    BinOpKind::ScAnd => format!("(truthy($t = {l}) ? {r} : $t)"),
                    BinOpKind::ScOr => format!("(truthy($t = {l}) ? $t : {r})"),
                    // `contains(container, item)`.
                    BinOpKind::In => format!("contains({r}, {l})"),
                    op => format!("{}({l}, {r})", binop_fn(op)),
                }
            }
            Expr::Compare(c) => {
                let [op] = c.ops.as_slice() else {
                    return Err("chained comparisons".into());
                };
                let l = self.expr(&c.expr, s)?;
                let r = self.expr(&op.expr, s)?;
                match op.op {
                    // `contains(container, item)`.
                    CompareOpKind::In | CompareOpKind::NotIn => {
                        format!("{}({r}, {l})", compare_fn(op.op))
                    }
                    _ => format!("{}({l}, {r})", compare_fn(op.op)),
                }
            }
            Expr::IfExpr(i) => format!(
                "(truthy({}) ? {} : {})",
                self.expr(&i.test_expr, s)?,
                self.expr(&i.true_expr, s)?,
                match &i.false_expr {
                    Some(f) => self.expr(f, s)?,
                    None => "undefined".into(),
                }
            ),
            Expr::Filter(f) => {
                if !FILTERS.contains(&f.name) {
                    return Err(format!("filter `{}`", f.name));
                }
                let value = match &f.expr {
                    Some(v) => self.expr(v, s)?,
                    None => "undefined".into(),
                };
                let args = self.args(&f.args, s)?;
                if f.name == "__loop" {
                    format!("o.loop({value})")
                } else {
                    format!("F[{}](o, {value}{args})", js_str(f.name))
                }
            }
            Expr::Test(t) => {
                if !TESTS.contains(&t.name) {
                    return Err(format!("test `{}`", t.name));
                }
                format!(
                    "TESTS[{}]({}{})",
                    js_str(t.name),
                    self.expr(&t.expr, s)?,
                    self.args(&t.args, s)?
                )
            }
            Expr::Call(c) => match &c.expr {
                // The compiler emits `can(action, resource)` for `r-can`;
                // it is the only global function (render/mod.rs, base_env).
                Expr::Var(v) if v.id == "can" => format!("can(o{})", self.args(&c.args, s)?),
                _ => return Err("function calls other than `can`".into()),
            },
            Expr::List(l) => {
                let items = l
                    .items
                    .iter()
                    .map(|i| self.expr(i, s))
                    .collect::<Result<Vec<_>, _>>()?;
                format!("[{}]", items.join(", "))
            }
            Expr::Tuple(t) => {
                let items = t
                    .items
                    .iter()
                    .map(|i| self.expr(i, s))
                    .collect::<Result<Vec<_>, _>>()?;
                format!("[{}]", items.join(", "))
            }
            Expr::Map(m) => {
                let mut pairs = Vec::new();
                for (k, v) in m.keys.iter().zip(&m.values) {
                    pairs.push(format!("[{}, {}]", self.expr(k, s)?, self.expr(v, s)?));
                }
                format!("mapOf([{}])", pairs.join(", "))
            }
            Expr::Slice(_) => return Err("slices".into()),
        })
    }

    fn args(&mut self, args: &[CallArg<'_>], s: &str) -> Result<String, String> {
        let mut out = String::new();
        for a in args {
            match a {
                CallArg::Pos(e) => {
                    let _ = write!(out, ", {}", self.expr(e, s)?);
                }
                _ => return Err("keyword and splat arguments".into()),
            }
        }
        Ok(out)
    }
}

fn binop_fn(op: BinOpKind) -> &'static str {
    match op {
        BinOpKind::Eq => "eq",
        BinOpKind::Ne => "ne",
        BinOpKind::Lt => "lt",
        BinOpKind::Lte => "le",
        BinOpKind::Gt => "gt",
        BinOpKind::Gte => "ge",
        BinOpKind::Add => "add",
        BinOpKind::Sub => "sub",
        BinOpKind::Mul => "mul",
        BinOpKind::Div => "div",
        BinOpKind::FloorDiv => "floorDiv",
        BinOpKind::Rem => "rem",
        BinOpKind::Pow => "pow",
        BinOpKind::Concat => "concat",
        BinOpKind::In | BinOpKind::ScAnd | BinOpKind::ScOr => {
            unreachable!("inlined in Cx::expr")
        }
    }
}

fn compare_fn(op: CompareOpKind) -> &'static str {
    match op {
        CompareOpKind::Eq => "eq",
        CompareOpKind::Ne => "ne",
        CompareOpKind::Lt => "lt",
        CompareOpKind::Lte => "le",
        CompareOpKind::Gt => "gt",
        CompareOpKind::Gte => "ge",
        CompareOpKind::In => "contains",
        CompareOpKind::NotIn => "notContains",
    }
}

fn var_name<'a>(e: &Expr<'a>) -> Result<&'a str, String> {
    match e {
        Expr::Var(v) => Ok(v.id),
        _ => Err("assignment to something other than a name".into()),
    }
}

fn const_str(e: &Expr<'_>) -> Option<String> {
    match e {
        Expr::Const(c) => c.value.as_str().map(str::to_string),
        _ => None,
    }
}

/// A JS string literal. JSON is a subset of JS since ES2019 (U+2028 and
/// U+2029 are allowed in string literals), and serde_json escapes quotes,
/// backslashes, and control characters, so template text cannot end the
/// literal.
fn js_str(s: &str) -> String {
    serde_json::to_string(s).expect("a string serializes")
}

fn const_js(v: &Value) -> Result<String, String> {
    Ok(match v.kind() {
        ValueKind::Undefined => "undefined".into(),
        ValueKind::None => "null".into(),
        ValueKind::Bool => if v.is_true() { "true" } else { "false" }.into(),
        ValueKind::String => js_str(v.as_str().unwrap_or_default()),
        ValueKind::Number => {
            let n = f64::try_from(v.clone()).map_err(|e| e.to_string())?;
            if !n.is_finite() {
                return Err("a non-finite number literal".into());
            }
            // `{n:?}` keeps the precision and is valid JS (`1e21` included).
            format!("{n:?}")
        }
        _ => return Err(format!("a constant of kind {}", v.kind())),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{CompiledTemplate, TemplateKind};

    fn one(source: &str) -> Result<String, EmitError> {
        let mut c = CompiledTemplates::default();
        c.templates.insert(
            "pages/index".into(),
            CompiledTemplate {
                kind: TemplateKind::Page,
                source: source.into(),
                fragments: None,
            },
        );
        emit_module(&c)
    }

    #[test]
    fn unsupported_constructs_are_refused() {
        for (src, reason) in [
            ("{{ d | date }}", "filter `date`"),
            ("{{ d | ago }}", "filter `ago`"),
            ("{{ xs[1:2] }}", "slices"),
            ("{% for a, b in xs %}{% endfor %}", "tuple loop targets"),
            ("{{ range(3) }}", "function calls other than `can`"),
        ] {
            let err = one(src).unwrap_err();
            assert_eq!(err.reason, reason, "{src}");
            assert_eq!(err.template, "pages/index");
        }
    }

    #[test]
    fn template_text_cannot_escape_the_string_literal() {
        let js = one("\"); globalThis.x = 1; (\"`${a}`</script>").unwrap();
        assert!(js.contains(r#"o.w("\"); globalThis.x = 1; (\"`${a}`</script>");"#));
    }

    #[test]
    fn names_are_quoted_keys_not_identifiers() {
        let js = one("{{ constructor }}{{ a.b }}").unwrap();
        assert!(js.contains(r#"o.emit(s["constructor"])"#));
        assert!(js.contains(r#"getItem(s["a"], "b")"#));
    }
}
