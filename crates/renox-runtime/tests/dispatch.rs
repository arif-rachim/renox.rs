const HELLO_HASH: &str = "802957869194e4c16e462dfcb50bfa6b3e435fca606b96a1223e2b7e21271d7a";

fn hello_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../docs/contracts/examples/hello-artifact")
        .join(HELLO_HASH)
}

fn runtime_with_sink() -> (Runtime, Arc<MemoryLogSink>) {
    let sink = Arc::new(MemoryLogSink::default());
    let rt = Runtime::new(RuntimeConfig {
        log_sink: sink.clone(),
    });
    (rt, sink)
}

/// Acceptance: the `examples/hello` artifact (the worked example of
/// `docs/contracts/artifact.md`) dispatches `{"ok":true}`.
#[tokio::test]
async fn hello_artifact_dispatches_ok_true() {
    let (rt, _) = runtime_with_sink();
    let iso = rt
        .create_isolate(spec(&hello_dir(), HELLO_HASH, Limits::FREE))
        .await
        .unwrap();
    let out = iso
        .dispatch(ctx("req_hello_000001"), get("/api/hello"))
        .await;
    assert_eq!(out.response.status(), 200);
    assert_eq!(body_json(&out.response), serde_json::json!({ "ok": true }));
    assert!(
        out.response.headers()["content-type"]
            .to_str()
            .unwrap()
            .starts_with("application/json")
    );
    assert_eq!(out.meter.status, MeterStatus::Ok);
    assert_eq!(out.meter.route.as_deref(), Some("GET /api/hello"));
}

/// `docs/23-failure-modes.md`: unknown route -> 404 generated by the runtime,
/// no tenant code runs; wrong method -> 405 with `Allow`.
#[tokio::test]
async fn unknown_route_is_404_and_wrong_method_is_405() {
    let (rt, _) = runtime_with_sink();
    let iso = rt
        .create_isolate(spec(&hello_dir(), HELLO_HASH, Limits::FREE))
        .await
        .unwrap();
    let out = iso
        .dispatch(ctx("req_404_00000001"), get("/api/nope"))
        .await;
    assert_eq!(out.response.status(), 404);
    assert_eq!(out.meter.route, None);
    let post = http::Request::builder()
        .method("POST")
        .uri("https://test.renox.app/api/hello")
        .body(Bytes::new())
        .unwrap();
    let out = iso.dispatch(ctx("req_405_00000001"), post).await;
    assert_eq!(out.response.status(), 405);
    assert_eq!(out.response.headers()["allow"], "GET, HEAD");
    // HEAD is served by GET with the body dropped.
    let head = http::Request::builder()
        .method("HEAD")
        .uri("https://test.renox.app/api/hello")
        .body(Bytes::new())
        .unwrap();
    let out = iso.dispatch(ctx("req_head_0000001"), head).await;
    assert_eq!(out.response.status(), 200);
    assert!(out.response.body().is_empty());
}

/// `docs/23-failure-modes.md`, "Handler throws": 500 `RENOX_INTERNAL` with
/// the request id; the message and stack go to the tenant log only.
#[tokio::test]
async fn handler_exception_is_500_without_leaking_message_or_stack() {
    let (rt, sink) = runtime_with_sink();
    let src = r#"
        export function GET() { throw new Error("secret-detail-xyz at /srv/internal"); }
        export function POST() { return { not: "a response" }; }
        export async function PUT() { await null; throw "a string"; }
    "#;
    let (dir, hash) = function_artifact(
        src,
        &[("GET", "/boom"), ("POST", "/boom"), ("PUT", "/boom")],
        &[],
    );
    let iso = rt
        .create_isolate(spec(&dir, &hash, Limits::FREE))
        .await
        .unwrap();
    for (method, id) in [
        ("GET", "req_throw_000001"),
        ("POST", "req_throw_000002"),
        ("PUT", "req_throw_000003"),
    ] {
        let req = http::Request::builder()
            .method(method)
            .uri("https://test.renox.app/boom")
            .body(Bytes::new())
            .unwrap();
        let out = iso.dispatch(ctx(id), req).await;
        assert_eq!(out.response.status(), 500, "{method}");
        assert_eq!(out.meter.status, MeterStatus::Error);
        let body = String::from_utf8(out.response.body().to_vec()).unwrap();
        assert!(!body.contains("secret-detail"), "{body}");
        assert!(!body.contains("/srv"), "{body}");
        assert!(!body.contains("a string"), "{body}");
        assert!(!body.contains("file://"), "{body}");
        let v = body_json(&out.response);
        assert_eq!(v["error"]["code"], "RENOX_INTERNAL");
        assert_eq!(v["error"]["request_id"], id);
    }
    let lines = sink.lines();
    let thrown = lines
        .iter()
        .find(|l| l.request_id.as_deref() == Some("req_throw_000001"))
        .expect("logged");
    assert_eq!(thrown.level, "error");
    assert!(
        thrown.fields["cause_message"]
            .as_str()
            .unwrap()
            .contains("secret-detail-xyz")
    );
    assert!(
        thrown.fields["stack"]
            .as_str()
            .unwrap()
            .contains("file:///functions/f.js")
    );
    assert!(
        lines
            .iter()
            .any(|l| l.request_id.as_deref() == Some("req_throw_000002")
                && l.message.contains("did not return a Response"))
    );
}

/// Acceptance: `Deno` and `SharedArrayBuffer` are not reachable from tenant
/// code (`docs/contracts/ops.md` section 11, global table), nor are the other
/// removed globals, `Deno.core`, or `ext:` modules; `performance.now()` is
/// coarsened to whole milliseconds.
#[tokio::test]
async fn hidden_globals_are_not_reachable() {
    let (rt, _) = runtime_with_sink();
    let src = r#"
        const atTopLevel = typeof Deno;
        export async function GET() {
            let shared = "absent";
            try { new WebAssembly.Memory({ initial: 1, maximum: 1, shared: true }); shared = "created"; } catch { }
            new WebAssembly.Memory({ initial: 1 });
            let ext = "refused";
            try { await import("ext:core/ops"); ext = "imported"; } catch { }
            let core = "absent";
            try { if (globalThis.Deno?.core || globalThis.__bootstrap || globalThis.__renoxInternal) core = "present"; } catch { }
            const node = {};
            for (const m of ["node:path", "node:buffer", "node:fs", "node:process", "node:child_process", "node:net", "node:vm"]) {
                try { await import(m); node[m] = "ok"; } catch { node[m] = "refused"; }
            }
            const nows = [];
            for (let i = 0; i < 2000; i++) nows.push(performance.now());
            return Response.json({
                atTopLevel,
                deno: typeof Deno,
                sab: typeof SharedArrayBuffer,
                shared,
                ext,
                core,
                websocket: typeof WebSocket,
                caches: typeof caches,
                localStorage: typeof localStorage,
                worker: typeof Worker,
                close: typeof close,
                prompt: typeof prompt,
                coarse: nows.every((n) => Number.isInteger(n)) && Number.isInteger(performance.timeOrigin),
                cpus: navigator.hardwareConcurrency,
                process: typeof process,
                gpu: typeof GPU,
                node,
            });
        }
    "#;
    let (dir, hash) = function_artifact(src, &[("GET", "/g")], &[]);
    let iso = rt
        .create_isolate(spec(&dir, &hash, Limits::FREE))
        .await
        .unwrap();
    let out = iso.dispatch(ctx("req_globals_0001"), get("/g")).await;
    assert_eq!(out.response.status(), 200, "{:?}", out.response.body());
    let v = body_json(&out.response);
    assert_eq!(v["atTopLevel"], "undefined");
    assert_eq!(v["deno"], "undefined");
    assert_eq!(v["sab"], "undefined");
    assert_eq!(v["shared"], "absent");
    assert_eq!(v["ext"], "refused");
    assert_eq!(v["core"], "absent");
    for k in [
        "websocket",
        "caches",
        "localStorage",
        "worker",
        "close",
        "prompt",
    ] {
        assert_eq!(v[k], "undefined", "{k}");
    }
    assert_eq!(v["coarse"], true);
    assert_eq!(v["cpus"], 1);
    assert_eq!(v["process"], "undefined");
    assert_eq!(v["gpu"], "undefined");
    assert_eq!(
        v["node"],
        serde_json::json!({ "node:path": "ok", "node:buffer": "ok", "node:fs": "refused", "node:process": "refused", "node:child_process": "refused", "node:net": "refused", "node:vm": "refused" })
    );
}

/// The module loader is restricted to the artifact's `code/`: no remote
/// imports, no `npm:`, no escape; a failing module fails creation (fail closed).
#[tokio::test]
async fn module_loader_is_restricted_to_the_artifact() {
    let (rt, _) = runtime_with_sink();
    for (src, what) in [
        (
            "import 'https://deno.land/x/a.js'; export const GET = () => new Response('');",
            "remote",
        ),
        (
            "import 'npm:left-pad'; export const GET = () => new Response('');",
            "npm",
        ),
        (
            "import '../../../../manifest.json' with { type: 'json' }; export const GET = () => new Response('');",
            "escape",
        ),
        (
            "export const POST = () => new Response('');",
            "missing export",
        ),
        ("throw new Error('top-level');", "top-level throw"),
    ] {
        let (dir, hash) = function_artifact(src, &[("GET", "/x")], &[]);
        let err = rt
            .create_isolate(spec(&dir, &hash, Limits::FREE))
            .await
            .err();
        assert!(err.is_some(), "{what} should fail creation");
    }
    // Relative imports and JSON modules inside code/ work.
    let manifest = serde_json::json!({
        "artifact": { "version": 0 },
        "app": { "name": "test", "timezone": "Asia/Dubai" },
        "code": { "format": "esm-dir", "entry": { "functions/f": "functions/f.js" } },
        "routes": [{ "kind": "function", "method": "GET", "path": "/x/:id", "module": "functions/f", "export": "GET" }],
        "permissions": { "network": [], "secrets": [] }
    });
    let manifest = serde_json::to_vec(&manifest).unwrap();
    let (dir, hash) = write_artifact(&[
        ("manifest.json", &manifest),
        ("code/functions/f.js", b"import { greet } from '../lib/greet.js'; import data from '../lib/data.json' with { type: 'json' };\nexport const GET = ({ params, url }) => Response.json({ msg: greet(params.id), n: data.n, meta: import.meta.url, q: url.searchParams.get('q') });"),
        ("code/lib/greet.js", b"export const greet = (n) => `hi ${n}`;"),
        ("code/lib/data.json", b"{\"n\": 7}"),
    ]);
    let iso = rt
        .create_isolate(spec(&dir, &hash, Limits::FREE))
        .await
        .unwrap();
    let out = iso
        .dispatch(ctx("req_import_00001"), get("/x/42?q=z"))
        .await;
    assert_eq!(
        body_json(&out.response),
        serde_json::json!({ "msg": "hi 42", "n": 7, "meta": "file:///functions/f.js", "q": "z" })
    );
}

/// `docs/contracts/ops.md`, "Verification by implementing issues" 1: the
/// request token survives `await`, timers, and promise continuations, and
/// a timer that outlives its request gets `RENOX_NO_REQUEST`.
#[tokio::test]
async fn request_scope_follows_async_context() {
    let (rt, _) = runtime_with_sink();
    let src = r#"
        let late = "pending";
        export async function GET(ctx) {
            const a = ctx.deadline.remainingMs();
            await new Promise((r) => setTimeout(r, 5));
            const b = ctx.deadline.remainingMs();
            const c = await new Promise((r) => setTimeout(() => r(ctx.deadline.remainingMs()), 1));
            setTimeout(() => { try { ctx.deadline.remainingMs(); late = "worked"; } catch (e) { late = e.code; } }, 30);
            return Response.json({ ok: a > 0 && b > 0 && c > 0 && b <= a });
        }
        export async function POST() {
            await new Promise((r) => setTimeout(r, 60));
            return Response.json({ late });
        }
    "#;
    let (dir, hash) = function_artifact(src, &[("GET", "/s"), ("POST", "/s")], &[]);
    let iso = rt
        .create_isolate(spec(&dir, &hash, Limits::FREE))
        .await
        .unwrap();
    let out = iso.dispatch(ctx("req_scope_000001"), get("/s")).await;
    assert_eq!(body_json(&out.response), serde_json::json!({ "ok": true }));
    let post = http::Request::builder()
        .method("POST")
        .uri("https://test.renox.app/s")
        .body(Bytes::new())
        .unwrap();
    let out = iso.dispatch(ctx("req_scope_000002"), post).await;
    assert_eq!(
        body_json(&out.response),
        serde_json::json!({ "late": "RENOX_NO_REQUEST" })
    );
}

/// Requests on one isolate run concurrently and each sees its own request.
#[tokio::test]
async fn concurrent_requests_keep_their_own_context() {
    let (rt, _) = runtime_with_sink();
    let src = r#"
        export async function GET({ params, req }) {
            await new Promise((r) => setTimeout(r, Number(params.ms)));
            return Response.json({ id: params.id, header: req.headers.get("x-test") });
        }
    "#;
    let (dir, hash) = function_artifact(src, &[("GET", "/c/:id/:ms")], &[]);
    let iso = Arc::new(
        rt.create_isolate(spec(&dir, &hash, Limits::FREE))
            .await
            .unwrap(),
    );
    let mut tasks = Vec::new();
    for i in 0..20u32 {
        let iso = iso.clone();
        tasks.push(tokio::spawn(async move {
            let req = http::Request::builder()
                .uri(format!("https://test.renox.app/c/{i}/{}", 20 - i))
                .header("x-test", format!("h{i}"))
                .body(Bytes::new())
                .unwrap();
            let out = iso.dispatch(ctx(&format!("req_conc_{i:08}")), req).await;
            (i, body_json(&out.response))
        }));
    }
    let started = Instant::now();
    for t in tasks {
        let (i, v) = t.await.unwrap();
        assert_eq!(
            v,
            serde_json::json!({ "id": i.to_string(), "header": format!("h{i}") })
        );
    }
    // Twenty sleeps of up to 20 ms overlap; serial execution would take ~210 ms.
    assert!(
        started.elapsed() < Duration::from_millis(200),
        "{:?}",
        started.elapsed()
    );
}

/// Request bodies and headers reach the handler; response headers and
/// status come back.
#[tokio::test]
async fn request_body_and_response_headers_round_trip() {
    let (rt, _) = runtime_with_sink();
    let src = r#"
        export async function POST({ req }) {
            const body = await req.json();
            return new Response(JSON.stringify({ got: body.n + 1 }), { status: 201, headers: { "x-out": "yes", "content-type": "application/json" } });
        }
    "#;
    let (dir, hash) = function_artifact(src, &[("POST", "/b")], &[]);
    let iso = rt
        .create_isolate(spec(&dir, &hash, Limits::FREE))
        .await
        .unwrap();
    let req = http::Request::builder()
        .method("POST")
        .uri("https://test.renox.app/b")
        .header("content-type", "application/json")
        .body(Bytes::from_static(b"{\"n\":41}"))
        .unwrap();
    let out = iso.dispatch(ctx("req_body_0000001"), req).await;
    assert_eq!(out.response.status(), 201);
    assert_eq!(out.response.headers()["x-out"], "yes");
    assert_eq!(body_json(&out.response), serde_json::json!({ "got": 42 }));
}

/// An `eszip` artifact (`code.format = "eszip"`) loads and dispatches.
#[tokio::test]
async fn eszip_artifact_dispatches() {
    let (rt, _) = runtime_with_sink();
    let (dir, hash) = eszip_hello_artifact();
    let iso = rt
        .create_isolate(spec(&dir, &hash, Limits::FREE))
        .await
        .unwrap();
    let out = iso
        .dispatch(ctx("req_eszip_000001"), get("/api/hello"))
        .await;
    assert_eq!(
        body_json(&out.response),
        serde_json::json!({ "ok": true, "via": "eszip" })
    );
}

fn eszip_hello_artifact() -> (PathBuf, String) {
    let mut archive = eszip::EszipV2::default();
    archive.add_to_front(
        eszip::ModuleKind::JavaScript,
        "file:///lib.js".into(),
        b"export const via = 'eszip';".to_vec(),
        Vec::new(),
    );
    archive.add_to_front(
        eszip::ModuleKind::JavaScript,
        "file:///functions/api/hello.js".into(),
        b"import { via } from '../../lib.js'; export const GET = () => Response.json({ ok: true, via });".to_vec(),
        Vec::new(),
    );
    let bytes = archive.into_bytes();
    let manifest = serde_json::json!({
        "artifact": { "version": 0 },
        "app": { "name": "hello", "timezone": "Asia/Dubai" },
        "code": { "format": "eszip", "entry": { "functions/api/hello": "functions/api/hello.js" } },
        "routes": [{ "kind": "function", "method": "GET", "path": "/api/hello", "module": "functions/api/hello", "export": "GET" }],
        "permissions": { "network": [], "secrets": [] }
    });
    let manifest = serde_json::to_vec(&manifest).unwrap();
    write_artifact(&[("manifest.json", &manifest), ("code/bundle.eszip", &bytes)])
}

/// Isolate creation time (p50/p99) for `esm-dir` and `eszip`, with V8 heap
/// statistics and RSS delta per isolate (feeds B1/B4 and the F1 gate, #35).
/// The numbers are printed; the assertions only catch gross regressions.
#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn isolate_creation_time_and_memory_are_printed() {
    let (rt, _) = runtime_with_sink();
    println!(
        "platform snapshot: {} bytes, built in {:?} (once per process)",
        rt.snapshot_bytes(),
        Runtime::snapshot_build_time().unwrap()
    );
    let (eszip_dir, eszip_hash) = eszip_hello_artifact();
    for (label, dir, hash) in [
        ("esm-dir", hello_dir(), HELLO_HASH.to_string()),
        ("eszip", eszip_dir, eszip_hash),
    ] {
        // Warm-up: first isolate pays one-time costs (code pages, allocator).
        drop(
            rt.create_isolate(spec(&dir, &hash, Limits::FREE))
                .await
                .unwrap(),
        );
        const N: usize = 30;
        let mut created = Vec::with_capacity(N);
        let mut inner = Vec::with_capacity(N);
        let mut kept = Vec::with_capacity(N);
        let rss_before = rss_bytes();
        for i in 0..N {
            let t = Instant::now();
            let iso = rt
                .create_isolate(spec(&dir, &hash, Limits::FREE))
                .await
                .unwrap();
            created.push(t.elapsed());
            inner.push(iso.stats().unwrap().create_time);
            let out = iso
                .dispatch(ctx(&format!("req_create_{i:06}")), get("/api/hello"))
                .await;
            assert_eq!(out.response.status(), 200);
            kept.push(iso);
        }
        // Give V8 background threads a moment, then measure.
        tokio::time::sleep(Duration::from_millis(200)).await;
        let rss_after = rss_bytes();
        let stats = kept[0].stats().unwrap();
        created.sort();
        inner.sort();
        let per_isolate =
            (rss_after.saturating_sub(rss_before)) as f64 / N as f64 / (1024.0 * 1024.0);
        println!(
            "[{label}] isolate creation (handle, incl. artifact verification): p50 {:?} p99 {:?}; on the isolate thread: p50 {:?} p99 {:?}; module eval {:?}",
            percentile(&created, 0.5),
            percentile(&created, 0.99),
            percentile(&inner, 0.5),
            percentile(&inner, 0.99),
            stats.module_time
        );
        println!(
            "[{label}] V8 heap after first request: used {:.2} MB, total {:.2} MB; RSS delta per live isolate: {per_isolate:.2} MB ({N} isolates)",
            stats.used_heap_bytes as f64 / 1048576.0,
            stats.total_heap_bytes as f64 / 1048576.0
        );
        assert!(percentile(&inner, 0.5) < Duration::from_secs(2));
        drop(kept);
    }
}
