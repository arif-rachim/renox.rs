//! `packaged` feature (#154): embed the platform snapshot and the residual
//! lazy extension sources in the binary, so `renox-worker` runs on a machine
//! without the cargo registry (README, "Packaging").
//!
//! Without the feature this script does nothing and `Runtime::new` builds
//! the snapshot at process start from the Deno crates' sources (the dev
//! path). With it, `RENOX_PACKAGED_DIR` must name a directory written by
//! `Runtime::write_packaged` from a build of the same source and features:
//!
//! - `snapshot.bin`: the V8 startup snapshot;
//! - `lazy.tsv`: one line per residual lazy source, `<js|esm>\t<specifier>\t<file>`,
//!   with `<file>` relative to the directory and already transpiled.
//!
//! The script writes `$OUT_DIR/packaged.rs` with `include_bytes!` and
//! `include_str!` of those files; `src/runtime.rs` includes it.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    if std::env::var_os("CARGO_FEATURE_PACKAGED").is_none() {
        return;
    }
    println!("cargo:rerun-if-env-changed=RENOX_PACKAGED_DIR");
    let Some(dir) = std::env::var_os("RENOX_PACKAGED_DIR") else {
        fail(
            "the `packaged` feature needs RENOX_PACKAGED_DIR (a directory written by Runtime::write_packaged)",
        );
    };
    let dir = std::fs::canonicalize(&dir).unwrap_or_else(|e| {
        fail(&format!(
            "RENOX_PACKAGED_DIR {}: {e}",
            Path::new(&dir).display()
        ))
    });
    let snapshot = existing(&dir, "snapshot.bin");
    let tsv_path = existing(&dir, "lazy.tsv");
    let tsv = std::fs::read_to_string(&tsv_path)
        .unwrap_or_else(|e| fail(&format!("{}: {e}", tsv_path.display())));

    let (mut js, mut esm) = (String::new(), String::new());
    for (n, line) in tsv.lines().enumerate().filter(|(_, l)| !l.is_empty()) {
        let mut cols = line.split('\t');
        let (Some(kind), Some(specifier), Some(file), None) =
            (cols.next(), cols.next(), cols.next(), cols.next())
        else {
            fail(&format!(
                "lazy.tsv line {}: expected 3 tab-separated columns",
                n + 1
            ));
        };
        if specifier.is_empty() || file.contains("..") || file.starts_with('/') {
            fail(&format!("lazy.tsv line {}: invalid entry", n + 1));
        }
        let path = existing(&dir, file);
        let out = match kind {
            "js" => &mut js,
            "esm" => &mut esm,
            _ => fail(&format!(
                "lazy.tsv line {}: kind {kind:?} is not js or esm",
                n + 1
            )),
        };
        writeln!(
            out,
            "    ({specifier:?}, include_str!({:?})),",
            path.display().to_string()
        )
        .unwrap();
    }

    let code = format!(
        "// Generated by build.rs from RENOX_PACKAGED_DIR={dir:?}.\n\
         pub(crate) static SNAPSHOT: &[u8] = include_bytes!({snapshot:?});\n\
         pub(crate) static LAZY_JS: &[(&str, &str)] = &[\n{js}];\n\
         pub(crate) static LAZY_ESM: &[(&str, &str)] = &[\n{esm}];\n",
        dir = dir.display().to_string(),
        snapshot = snapshot.display().to_string(),
    );
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("packaged.rs");
    std::fs::write(&out, code).unwrap_or_else(|e| fail(&format!("{}: {e}", out.display())));
}

/// `dir/rel`, which must be a file; rebuilt when it changes.
fn existing(dir: &Path, rel: &str) -> PathBuf {
    let path = dir.join(rel);
    if !path.is_file() {
        fail(&format!("{} is missing", path.display()));
    }
    println!("cargo:rerun-if-changed={}", path.display());
    path
}

fn fail(msg: &str) -> ! {
    eprintln!("renox-runtime build.rs: {msg}");
    std::process::exit(1);
}
