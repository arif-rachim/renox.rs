#!/usr/bin/env bash
# Derives the seccomp allowlist of renox-worker (#253) by tracing what it
# actually calls: `strace -f -qq -c` around
#   1. every test binary of renox-cell (the worker in-process: two tenants,
#      pages, streaming, TLS, controlled and degraded mode, activation, ...),
#   2. the CLI's end-to-end tests that drive a real renox-worker binary
#      (`renox dev`, `renox deploy`), through a RENOX_WORKER_PATH wrapper,
#   3. each bench scenario that drives renox-worker (B8, B15, B16), when its
#      load generator is installed (skipped, and listed as skipped, otherwise),
# then writes the sorted union, plus crates/renox-cell/sandbox/baseline.txt
# (calls the worker makes only on paths the traces cannot reach, each with
# its reason), to crates/renox-cell/sandbox/syscalls.<arch>.txt.
#
#   ops/scripts/trace-syscalls.sh [--out <dir>] [--from-traces <dir>]
#
# --from-traces rebuilds the lists from traces of an earlier run (after an
# edit of baseline.txt) without tracing again. On x86_64 the script also
# derives syscalls.aarch64.txt from the x86_64 union with the table below
# (x86_64-only calls replaced by their *at / p* forms), until a trace on an
# arm64 host replaces it.
#
# Prints a summary for bench/results/<date>-syscall-profile.md: what was
# traced, what was skipped, and the syscall count.
set -euo pipefail

repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
out=$(mktemp -d)
from=""
while [[ $# -gt 0 ]]; do
  case $1 in
    --out) out=$2; shift 2 ;;
    --from-traces) from=$2; shift 2 ;;
    *) echo "usage: $0 [--out <dir>] [--from-traces <dir>]" >&2; exit 2 ;;
  esac
done
if [[ -n $from ]]; then out=$from; fi
mkdir -p "$out/traces"
command -v strace >/dev/null || { echo "trace-syscalls: strace is not installed" >&2; exit 1; }

case $(uname -m) in
  x86_64) arch=x86_64 ;;
  aarch64) arch=aarch64 ;;
  *) echo "trace-syscalls: unsupported architecture $(uname -m)" >&2; exit 1 ;;
esac

cd "$repo"
traced=()
skipped=()

# strace -c prints a table whose last column is the syscall name.
names() { awk 'NF >= 4 && $NF ~ /^[a-z_][a-z0-9_]*$/ && $NF != "syscall" && $NF != "total" { print $NF }' "$@"; }

if [[ -z $from ]]; then
# 1. renox-cell's test binaries.
cargo build --locked -q -p renox-cell --bin renox-worker
mapfile -t bins < <(cargo test --locked -q -p renox-cell --no-run --message-format=json 2>/dev/null \
  | bun -e 'for (const l of (await Bun.stdin.text()).split("\n")) { if (!l) continue; const m = JSON.parse(l); if (m.reason === "compiler-artifact" && m.executable && m.profile?.test) console.log(m.executable); }')
for bin in "${bins[@]}"; do
  name=$(basename "$bin")
  if strace -f -qq -c -o "$out/traces/test-$name.txt" "$bin" --test-threads=4 >"$out/traces/test-$name.log" 2>&1; then
    traced+=("cargo test -p renox-cell: ${name%-*}")
  else
    traced+=("cargo test -p renox-cell: ${name%-*} (tests failed; trace kept)")
  fi
done

# 2. and 3. A wrapper that traces every renox-worker the CLI or a scenario starts.
wrapper=$out/renox-worker
cat > "$wrapper" <<WRAPPER
#!/usr/bin/env bash
exec strace -f -qq -c -o "$out/traces/worker-\$\$.txt" "$repo/target/debug/renox-worker" "\$@"
WRAPPER
chmod +x "$wrapper"

for t in cli/tests/dev.e2e.test.ts cli/tests/deploy.e2e.test.ts; do
  if [[ -f $t ]] && RENOX_WORKER_PATH=$wrapper bun test "$t" >"$out/traces/$(basename "$t").log" 2>&1; then
    traced+=("bun test $t (renox-worker traced)")
  else
    skipped+=("bun test $t: failed or missing, see $out/traces/$(basename "$t").log")
  fi
done

for id in B8 B15 B16; do
  need=""
  case $id in
    B8) need=oha ;;
  esac
  if [[ -n $need ]] && ! command -v "$need" >/dev/null; then
    skipped+=("bench/run.sh $id: $need is not installed")
    continue
  fi
  if RENOX_WORKER_PATH=$wrapper bench/run.sh "$id" --runs 1 >"$out/traces/bench-$id.log" 2>&1; then
    traced+=("bench/run.sh $id --runs 1 (renox-worker traced)")
  else
    skipped+=("bench/run.sh $id: failed, see $out/traces/bench-$id.log")
  fi
done

else
  traced+=("(reused traces of $from)")
fi

# Union, plus the reviewed baseline.
list=crates/renox-cell/sandbox/syscalls.$arch.txt
{
  echo "# seccomp allowlist of renox-worker on $arch (#253): generated by ops/scripts/trace-syscalls.sh"
  echo "# on $(date -u +%Y-%m-%d) ($(uname -r)), the union of the traces plus sandbox/baseline.txt."
  echo "# Do not edit by hand; re-run the script and record it in bench/results/*-syscall-profile.md."
  {
    names "$out"/traces/*.txt
    grep -v '^#' crates/renox-cell/sandbox/baseline.txt | awk 'NF { print $1 }'
  } | sort -u
} > "$list"

count=$(grep -vc '^#' "$list")

# x86_64 -> aarch64: calls aarch64 does not have, and their replacement.
if [[ $arch == x86_64 ]]; then
  derived=crates/renox-cell/sandbox/syscalls.aarch64.txt
  {
    echo "# seccomp allowlist of renox-worker on aarch64 (#253): DERIVED by ops/scripts/trace-syscalls.sh"
    echo "# from syscalls.x86_64.txt on $(date -u +%Y-%m-%d) (x86_64-only calls mapped to their aarch64 forms);"
    echo "# replace it with a trace on an arm64 host. Do not edit by hand."
    grep -v '^#' "$list" | awk '
      BEGIN {
        m["access"] = "faccessat"; m["arch_prctl"] = ""; m["chmod"] = "fchmodat"; m["dup2"] = "dup3";
        m["epoll_wait"] = "epoll_pwait"; m["mkdir"] = "mkdirat"; m["poll"] = "ppoll"; m["readlink"] = "readlinkat";
        m["rename"] = "renameat"; m["symlink"] = "symlinkat"; m["unlink"] = "unlinkat"; m["open"] = "openat";
        m["stat"] = "newfstatat"; m["lstat"] = "newfstatat"; m["pipe"] = "pipe2"; m["epoll_create"] = "epoll_create1";
        m["fork"] = "clone"; m["vfork"] = "clone"; m["getdents"] = "getdents64"; m["select"] = "pselect6";
        m["eventfd"] = "eventfd2"; m["signalfd"] = "signalfd4"; m["inotify_init"] = "inotify_init1";
        m["chown"] = "fchownat"; m["lchown"] = "fchownat"; m["link"] = "linkat"; m["rmdir"] = "unlinkat";
        m["time"] = ""; m["alarm"] = ""; m["creat"] = "openat"; m["futimesat"] = ""; m["utimes"] = "utimensat";
      }
      { n = ($1 in m) ? m[$1] : $1; if (n != "") print n }
      END { print "clone"; print "faccessat2"; print "renameat2"; print "epoll_pwait2" }' | sort -u
  } > "$derived"
fi
echo "## Traced"
printf -- '- %s\n' "${traced[@]}"
echo "## Skipped"
if [[ ${#skipped[@]} -eq 0 ]]; then echo "- none"; else printf -- '- %s\n' "${skipped[@]}"; fi
echo "## Result"
echo "- $list: $count syscalls ($(names "$out"/traces/*.txt | sort -u | wc -l) traced)"
echo "- raw traces: $out/traces"
