// bun examples/home-services/sync-template.ts: writes cli/templates/home-services/
// from this example, the one source of `renox new <name> --template home-services`
// (#566). `cli/tests/examples.test.ts` fails when the two differ; run this, then
// commit both.
//
// Every file of the app is copied except the workspace-only ones (EXCLUDED: the
// files `renox new` writes itself, package.json and tsconfig.json, the type
// files `renox check` and `renox dev` generate under .renox/types, the
// workspace's test config, the snapshots `renox test` writes on the first run)
// and this script. `renox.lock` is copied: `renox check` generates the module
// types (`renox:modules`) from it. A text file becomes
// `<path>.tpl`; a binary one (BINARY) becomes `<path>.base64.tpl`, its bytes in
// base64, which `renox new` decodes. `renox.toml` gets `name = "{{APP}}"`.
// `files.ts` imports them all as text (so the compiled CLI embeds them) and is
// generated here too.
import { type Dirent, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

export const EXAMPLE_DIR = import.meta.dir;
export const TEMPLATE_DIR = join(import.meta.dir, "../../cli/templates/home-services");

/** Paths (relative to the example) that stay out of the template. */
export const EXCLUDED = ["package.json", "tsconfig.json", "renox-modules.d.ts", "text-imports.d.ts", "bunfig.toml", "sync-template.ts"] as const;
const EXCLUDED_DIR = /^(node_modules|\.renox|tests\/__snapshots__)(\/|$)/u;

/** Extensions whose files are copied as base64. */
export const BINARY = /\.(png|jpe?g|webp|gif|ico|woff2?|ttf|otf|pdf)$/u;

/** The example's files that make the template, sorted. */
export function templateFiles(): string[] {
  return (readdirSync(EXAMPLE_DIR, { recursive: true, withFileTypes: true }) as Dirent[])
    .filter((d) => d.isFile())
    .map((d) => relative(EXAMPLE_DIR, join(d.parentPath, d.name)).split("\\").join("/"))
    .filter((f) => !EXCLUDED_DIR.test(f) && !(EXCLUDED as readonly string[]).includes(f))
    .sort();
}

/** What the template holds for one example file: its file name under TEMPLATE_DIR and its content. */
export function templateEntry(rel: string): { file: string; content: string } {
  const bytes = readFileSync(join(EXAMPLE_DIR, rel));
  if (BINARY.test(rel)) return { file: `${rel}.base64.tpl`, content: `${bytes.toString("base64")}\n` };
  let text = bytes.toString("utf8");
  if (rel === "renox.toml") {
    const named = text.replace(/^name = "home-services"$/mu, 'name = "{{APP}}"');
    if (named === text) throw new Error('renox.toml: no line name = "home-services" to replace');
    text = named;
  }
  return { file: `${rel}.tpl`, content: text };
}

/** cli/templates/home-services/files.ts: every template file imported as text, keyed by its path in the new app. */
export function filesModule(files: readonly string[]): string {
  const lines = [
    "// Generated by examples/home-services/sync-template.ts (#566); do not edit.",
    "// The files of `renox new <name> --template home-services`: path in the new",
    "// app → content. A path in HOME_SERVICES_BINARY holds base64.",
    "",
  ];
  files.forEach((rel, i) => lines.push(`import f${i} from "./${templateEntry(rel).file}" with { type: "text" };`));
  lines.push("", "export const HOME_SERVICES: Readonly<Record<string, string>> = {");
  files.forEach((rel, i) => lines.push(`  ${JSON.stringify(rel)}: f${i},`));
  lines.push("};", "", "export const HOME_SERVICES_BINARY: readonly string[] = [");
  for (const rel of files.filter((f) => BINARY.test(f))) lines.push(`  ${JSON.stringify(rel)},`);
  lines.push("];", "");
  return lines.join("\n");
}

if (import.meta.main) {
  const files = templateFiles();
  rmSync(TEMPLATE_DIR, { recursive: true, force: true });
  for (const rel of files) {
    const { file, content } = templateEntry(rel);
    const out = join(TEMPLATE_DIR, file);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, content);
  }
  writeFileSync(join(TEMPLATE_DIR, "files.ts"), filesModule(files));
  console.log(`wrote ${files.length} files to cli/templates/home-services/`);
}
